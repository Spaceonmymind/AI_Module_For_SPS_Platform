import g4f

def detect_with_gpt(text: str) -> str:
    prompt = (
        "Определи, написан ли текст человеком или сгенерирован искусственным интеллектом. "
        "Проанализируй строго и аргументированно, без лишних вступлений.\n\n"
        "Важно: текст мог быть написан человеком ПО СТРОГОМУ ШАБЛОНУ (повторяющиеся вопросы/разделы, одинаковая структура карточек). "
        "Сам факт шаблонности и последовательности НЕ является признаком ИИ сам по себе — не учитывай это как доказательство без других индикаторов.\n\n"
        "Критерии анализа:\n"
        "1) Структура — последовательность и логика; отличай полезную структурированность от механической шаблонности.\n"
        "2) Стиль и язык — нейтральность/повторяемость/клише vs живая речь и личные обороты.\n"
        "3) Креативность — оригинальные идеи, личные примеры, неожиданные детали.\n"
        "4) Детализация — конкретика и привязка к реальности vs общие фразы.\n"
        "5) Ошибки и шероховатости — естественные оговорки/опечатки/неровности (человек) vs чрезмерная гладкость и однотипность (ИИ).\n\n"
        "Формат ответа (строго придерживайся):\n"
        "Структура: <1–2 коротких аргумента>\n"
        "Стиль и язык: <...>\n"
        "Креативность: <...>\n"
        "Детализация: <...>\n"
        "Ошибки и шероховатости: <...>\n"
        "Вердикт: текст скорее всего написан человеком | текст скорее всего сгенерирован ИИ\n"
        "Уверенность: <число от 0 до 100>\n\n"
        f"Текст:\n{text}"
    )

    try:
        response = g4f.ChatCompletion.create(
            model="gemini-2.0",
            messages=[{"role": "user", "content": prompt}],
            stream=False
        )
        return response
    except Exception as e:
        return f"Ошибка ChatGPT (g4f): {str(e)}"
